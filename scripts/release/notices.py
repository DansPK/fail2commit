#!/usr/bin/env python3
"""Generate deterministic dependency license notices from Cargo metadata."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

LICENSE_NAME = re.compile(r"^(licen[cs]e|copying|notice|copyright)([._-].*)?$", re.I)
COPYLEFT = re.compile(r"(^|[^A-Z])(A?GPL|LGPL|MPL|EPL|CDDL)(?:-|[^A-Z]|$)", re.I)
MAX_LICENSE_BYTES = 1024 * 1024


def metadata(repo: Path) -> dict:
    command = ["cargo", "metadata", "--format-version", "1", "--locked"]
    result = subprocess.run(command, cwd=repo, check=True, capture_output=True, text=True)
    return json.loads(result.stdout)


def license_files(crate_dir: Path) -> list[Path]:
    files: list[Path] = []
    for child in crate_dir.iterdir():
        if child.is_file() and LICENSE_NAME.match(child.name):
            files.append(child)
    return sorted(files, key=lambda path: path.name.casefold())


def read_license(path: Path) -> str:
    if path.stat().st_size > MAX_LICENSE_BYTES:
        raise ValueError(f"license file exceeds {MAX_LICENSE_BYTES} bytes: {path}")
    return path.read_text(encoding="utf-8", errors="replace").rstrip()


def generate(repo: Path) -> tuple[str, list[str]]:
    data = metadata(repo)
    workspace = set(data["workspace_members"])
    packages = sorted(
        (package for package in data["packages"] if package["id"] not in workspace),
        key=lambda package: (package["name"].casefold(), package["version"], package["id"]),
    )
    flags: list[str] = []
    sections: list[str] = []
    license_texts: dict[str, tuple[str, set[str]]] = {}

    for package in packages:
        expression = package.get("license") or "UNKNOWN"
        crate_dir = Path(package["manifest_path"]).resolve().parent
        paths: list[Path] = []
        declared_file = package.get("license_file")
        if declared_file:
            candidate = (crate_dir / declared_file).resolve()
            try:
                candidate.relative_to(crate_dir)
            except ValueError as error:
                raise ValueError(f"license_file escapes crate directory: {candidate}") from error
            if candidate.is_file():
                paths.append(candidate)
        for candidate in license_files(crate_dir):
            if candidate.resolve() not in {path.resolve() for path in paths}:
                paths.append(candidate)

        concerns: list[str] = []
        if expression == "UNKNOWN":
            concerns.append("unknown license expression")
        if COPYLEFT.search(expression):
            concerns.append("copyleft license expression")
        if not paths:
            concerns.append("no license text found in crate source")
        if concerns:
            flags.append(f"{package['name']} {package['version']}: {', '.join(concerns)}")

        body = [
            f"## {package['name']} {package['version']}",
            "",
            f"- License expression: `{expression}`",
            f"- Cargo source: `{package.get('source') or 'path'}`",
            "",
        ]
        if paths:
            for path in paths:
                text = read_license(path)
                digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
                if digest not in license_texts:
                    license_texts[digest] = (text, set())
                license_texts[digest][1].add(path.name)
                body.append(f"- License file `{path.name}`: text `{digest[:12]}`")
            body.append("")
        else:
            body.extend(["_No license file was present in the resolved crate source._", ""])
        sections.append("\n".join(body))

    header = [
        "# Third-Party Notices",
        "",
        "Generated by `scripts/release/notices.py` from `cargo metadata --format-version 1 --locked`.",
        "The fail2commit product is licensed under Apache-2.0; see `LICENSE`.",
        "The inherited project template notice is MIT; see `LICENSE.template-MIT`.",
        "Dependency license expressions and bundled license texts follow.",
        "",
        "## Review flags",
        "",
    ]
    if flags:
        header.extend(f"- {flag}" for flag in flags)
    else:
        header.append("- None (no copyleft or unknown dependency licenses detected).")
    header.extend(["", f"## Dependencies ({len(packages)})", ""])
    appendix = ["# License texts", ""]
    for digest, (license_text, names) in license_texts.items():
        appendix.extend(
            [
                f"## Text `{digest[:12]}`",
                "",
                f"Source filenames: {', '.join(f'`{name}`' for name in sorted(names, key=str.casefold))}",
                "",
                "```text",
                license_text,
                "```",
                "",
            ]
        )
    return "\n".join(header + sections + appendix).rstrip() + "\n", flags


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="THIRD-PARTY-NOTICES.md")
    args = parser.parse_args()
    repo = Path(__file__).resolve().parents[2]
    output = (repo / args.output).resolve()
    text, flags = generate(repo)
    output.write_text(text, encoding="utf-8", newline="\n")
    if flags:
        print("license review flags:", file=sys.stderr)
        for flag in flags:
            print(f"- {flag}", file=sys.stderr)
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
